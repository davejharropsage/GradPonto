// Writes MailerSend-ready copies of GradPonto's two emails into ./emails, with {{ placeholders }}
// in place of the real values.
//
//   npm run emails:export
//
// The HTML comes from the same source the app uses to send real emails
// (src/lib/auth/email-content.ts), so the two can never drift apart.

import { mkdirSync, writeFileSync } from "node:fs";
import { loginCodeContent, welcomeContent } from "../src/lib/auth/email-content.ts";

const outDir = new URL("../emails/", import.meta.url);
mkdirSync(outDir, { recursive: true });

const login = loginCodeContent({ code: "{{ code }}", minutes: "{{ minutes }}" });
const welcome = welcomeContent({ name: "{{ name }}", university: "{{ university }}", email: "{{ email }}", appUrl: "{{ app_url }}" });

// MailerSend renders templates with Twig, where {% ... %} and {# ... #} are also special.
// The emails must contain none of those, or the template would break when sent.
for (const [name, content] of [["login-code", login], ["welcome", welcome]]) {
  for (const field of ["html", "text", "subject"]) {
    if (/\{%|\{#|%\}|#\}/.test(content[field])) {
      console.error(`X ${name} ${field} contains a Twig control sequence ({% or {#). Fix the template.`);
      process.exit(1);
    }
  }
}

writeFileSync(new URL("login-code.html", outDir), login.html);
writeFileSync(new URL("login-code.txt", outDir), login.text);
writeFileSync(new URL("welcome.html", outDir), welcome.html);
writeFileSync(new URL("welcome.txt", outDir), welcome.text);

const readme = `# GradPonto email templates (MailerSend-ready)

Generated by \`npm run emails:export\` from \`src/lib/auth/email-content.ts\`. Do not edit these files by
hand: change the source, then run the export again.

## The two emails

| Template | Sent when | Subject | Variables |
|---|---|---|---|
| \`login-code\` | Someone asks to sign in | \`${login.subject}\` | \`{{ code }}\`, \`{{ minutes }}\` |
| \`welcome\` | Registration is completed (once) | \`${welcome.subject}\` | \`{{ name }}\`, \`{{ university }}\`, \`{{ email }}\`, \`{{ app_url }}\` |

Each has an \`.html\` version and a plain-text \`.txt\` version (email clients and spam filters like having both).

## Using them in MailerSend

1. **Templates > Create template > Custom HTML** (the "code your own" editor).
2. Paste the contents of the \`.html\` file. Paste the \`.txt\` file into the plain-text version.
3. Set the subject line from the table above. Variables work in the subject, HTML and text.
4. Save, then use **Send test email** to preview it.

## Important: templates and SMTP

MailerSend supports templates only through its **Email API**, not through SMTP
(https://developers.mailersend.com/smtp-relay). GradPonto sends over SMTP, so it does not use a template
saved inside MailerSend. It sends the same HTML itself, filled in with the real values. So:

- What users receive is always exactly this design, wherever it is sent from.
- A copy in MailerSend is useful for previewing and for testing, or if you later switch GradPonto to the
  MailerSend API and want the template stored there.

## Fonts and images

Email clients ignore web fonts and often block images, so these use system fonts and no images. The logo
mark is built from a table cell, so it always shows.
`;
writeFileSync(new URL("README.md", outDir), readme);

console.log("Wrote emails/login-code.html, login-code.txt, welcome.html, welcome.txt and README.md");
console.log(`  login-code  subject: ${login.subject}`);
console.log(`  welcome     subject: ${welcome.subject}`);
const vars = (s) => [...new Set([...s.matchAll(/\{\{\s*(\w+)\s*\}\}/g)].map((m) => m[1]))].sort().join(", ");
console.log(`  login-code  variables: ${vars(login.html + login.text + login.subject)}`);
console.log(`  welcome     variables: ${vars(welcome.html + welcome.text + welcome.subject)}`);
